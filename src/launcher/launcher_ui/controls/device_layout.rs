pub(super) fn key_label(input: Key) -> &'static str {
    match input {
        ShiftLeft => "Left Shift",
        ShiftRight => "Right Shift",
        AltLeft => "Left Alt",
        AltRight => "Right Alt",
        ControlLeft => "Left Ctrl",
        ControlRight => "Right Ctrl",
        SuperLeft => "Left Super",
        SuperRight => "Right Super",
        ArrowUp => "Up",
        ArrowDown => "Down",
        ArrowLeft => "Left Arrow",
        ArrowRight => "Right Arrow",
        Numpad0 => "Numpad 0",
        Numpad1 => "Numpad 1",
        Numpad2 => "Numpad 2",
        Numpad3 => "Numpad 3",
        Numpad4 => "Numpad 4",
        Numpad5 => "Numpad 5",
        Numpad6 => "Numpad 6",
        Numpad7 => "Numpad 7",
        Numpad8 => "Numpad 8",
        Numpad9 => "Numpad 9",
        NumpadAdd => "Numpad +",
        NumpadSubtract => "Numpad -",
        NumpadMultiply => "Numpad *",
        NumpadDivide => "Numpad /",
        NumpadDecimal => "Numpad .",
        NumpadEnter => "Numpad Enter",
        MouseLeft => "Mouse Left",
        MouseMiddle => "Mouse Middle",
        MouseRight => "Mouse Right",
        MouseForward => "Mouse Forward",
        MouseBack => "Mouse Back",
        MouseMotion => "Mouse Motion",
        _ => {
            KEYBOARD
                .iter()
                .find(|key| key.input == Some(input))
                .expect("configured key has a keyboard position")
                .label
        }
    }
}
